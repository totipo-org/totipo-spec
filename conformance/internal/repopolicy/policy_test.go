func put(t *testing.T, root, path, body string) {
	t.Helper()
	p := filepath.Join(root, path)
	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0600); err != nil {
		t.Fatal(err)
	}
}
func tree(t *testing.T) string {
	t.Helper()
	// Disposable trees have no workspace vendor; they inspect their own modules.
	t.Setenv("GOFLAGS", "-mod=readonly")
	r := t.TempDir()
	put(t, r, "generator/go.mod", "module totipo/generator\n\ngo 1.23.0\n")
	put(t, r, "conformance/go.mod", "module totipo/conformance\n\ngo 1.23.0\nrequire golang.org/x/crypto v0.36.0\nrequire golang.org/x/sys v0.31.0 // indirect\n")
	put(t, r, "go.work", "go 1.23.0\nuse (\n./generator\n./conformance\n)\n")
	put(t, r, "generator/a.go", "package generator\n")
	put(t, r, "conformance/a.go", "package conformance\n")
	return r
}
